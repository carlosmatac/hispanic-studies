const WORDING = new Map(ARCHIVE_WORDING.map(([stored, en, es]) => [stored, { en: en ?? stored, es }]));
const MONTHS_ES: Record<string, string> = {
  January: 'enero', February: 'febrero', March: 'marzo', April: 'abril', May: 'mayo', June: 'junio',
  July: 'julio', August: 'agosto', September: 'septiembre', October: 'octubre', November: 'noviembre', December: 'diciembre',
};

/** An edition's label or a companion's note, as readers of this language see it (the stored text when the table has no entry). */
export const archiveWording = (stored: string, lang: Lang) => WORDING.get(stored)?.[lang] ?? stored;

/** A curated work's date as shown ("4 May 1493" → "4 de mayo de 1493" in Spanish). */
export function archiveDate(stored: string, lang: Lang) {
  const known = WORDING.get(stored);
  if (known) return known[lang];
  if (lang === 'en') return stored;
  return stored.replace(/\b(\d{1,2}) (January|February|March|April|May|June|July|August|September|October|November|December) (\d{3,4})\b/g,
    (_, d: string, m: string, y: string) => `${d} de ${MONTHS_ES[m]} de ${y}`);
}
